INSERT INTO config.DashboardRolElemento (rol_id,dashboard_elemento_id,visible,orden)
SELECT R.rol_id,E.dashboard_elemento_id,1,M.orden
FROM @RolElemento M
INNER JOIN seg.Rol R WITH (NOLOCK) ON R.codigo=M.rol_codigo AND R.estado=1
INNER JOIN config.DashboardElemento E WITH (NOLOCK) ON E.codigo=M.elemento_codigo AND E.estado=1
WHERE NOT EXISTS (
    SELECT 1 FROM config.DashboardRolElemento X WITH (NOLOCK)
    WHERE X.rol_id=R.rol_id AND X.dashboard_elemento_id=E.dashboard_elemento_id
);
